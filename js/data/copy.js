/** c('key', {vars}, 'ai') → text with {vars} filled; arrays are filled item by item. */
export function c(key, vars = {}, mod) {
  let v = T[key];
  if (v && typeof v === 'object' && !Array.isArray(v)) v = v[mod] || v.rmm;
  const fill = s => s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
  if (Array.isArray(v)) return v.map(fill);
  return v === undefined ? key : fill(v);
}
